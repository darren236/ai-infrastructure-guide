#!/usr/bin/env bash

# Estimate data-driven duration bins, then profile safe per-bin batch sizes on
# the allocated GPU. Run this once through nemotron-profile.sbatch.
set -euo pipefail

WORK="${WORK:-$HOME/work/nemotron-poc}"
SOURCE="${SOURCE:-$HOME/work/nemo-speech-src}"
DATA="${DATA:-$HOME/data/nsc}"
CACHE="${CACHE:-$HOME/hf-cache}"
IMAGE="${IMAGE:-nvcr.io/nvidia/nemo-speech:26.07.00}"
PROFILE_DIR="${PROFILE_DIR:-$WORK/results/full_finetune/profile}"
CONTAINER_MEMORY="${CONTAINER_MEMORY:-24g}"
CONTAINER_NAME="${CONTAINER_NAME:-nemotron-profile-${SLURM_JOB_ID:-manual}}"

MODEL_RELATIVE="models--nvidia--nemotron-3.5-asr-streaming-0.6b/snapshots/ea30d66debe3740a08b573244286791d423d6b3e/nemotron-3.5-asr-streaming-0.6b.nemo"
TRAIN_MANIFEST="/data/nsc/full/nemo/train_ready.jsonl"
MODEL_PATH="/cache/$MODEL_RELATIVE"

mkdir -p "$PROFILE_DIR"

echo "Estimating 12 duration bins from all 2,152 training recordings..."
docker run --rm \
  --name "${CONTAINER_NAME}-bins" \
  --memory "$CONTAINER_MEMORY" \
  --memory-swap "$CONTAINER_MEMORY" \
  -v "$SOURCE:/nemo-src:ro" \
  -v "$DATA:/data/nsc:ro" \
  "$IMAGE" \
  /opt/venv/bin/python \
    /nemo-src/scripts/speech_recognition/estimate_duration_bins.py \
    "$TRAIN_MANIFEST" \
    --buckets 12 \
    --num_examples -1 \
    --min_duration 0.1 \
    --max_duration 39.99 \
  2>&1 | tee "$PROFILE_DIR/duration-bins.log"

bucket_duration_bins="$(sed -n 's/^[[:space:]]*bucket_duration_bins=//p' "$PROFILE_DIR/duration-bins.log" | tail -n 1)"
[[ -n "$bucket_duration_bins" ]] || {
  echo "Could not parse bucket_duration_bins from duration-bins.log" >&2
  exit 1
}

echo "Profiling the pinned .nemo model at 85% of L4 VRAM..."
docker run --rm --gpus all \
  --name "$CONTAINER_NAME" \
  --memory "$CONTAINER_MEMORY" \
  --memory-swap "$CONTAINER_MEMORY" \
  --shm-size=2g \
  --ulimit memlock=-1 \
  --ulimit stack=67108864 \
  -v "$SOURCE:/nemo-src:ro" \
  -v "$CACHE:/cache:ro" \
  "$IMAGE" \
  /opt/venv/bin/python \
    /nemo-src/scripts/speech_recognition/oomptimizer.py \
    --pretrained-name "$MODEL_PATH" \
    --buckets "$bucket_duration_bins" \
    --optimizer-name adamw \
    --start-batch-size 1 \
    --ratio 12 \
    --memory-fraction 0.85 \
    --dtype bfloat16 \
    --no-ddp \
  2>&1 | tee "$PROFILE_DIR/oomptimizer.log"

profile_bins="$(sed -n 's/^[[:space:]]*bucket_duration_bins=//p' "$PROFILE_DIR/oomptimizer.log" | tail -n 1)"
profile_sizes="$(sed -n 's/^[[:space:]]*bucket_batch_size=//p' "$PROFILE_DIR/oomptimizer.log" | tail -n 1)"

[[ -n "$profile_bins" && -n "$profile_sizes" ]] || {
  echo "OOMptimizer completed without a parseable final profile" >&2
  exit 1
}

profile_env="$PROFILE_DIR/batch-profile.env"
{
  echo "# Generated by NeMo Speech v3.0.0 OOMptimizer; do not hand-edit."
  echo "BUCKET_DURATION_BINS='$profile_bins'"
  echo "BUCKET_BATCH_SIZE='$profile_sizes'"
} > "$profile_env"

echo "Saved training profile: $profile_env"
sha256sum "$profile_env"
